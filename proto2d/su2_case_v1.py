#!/usr/bin/env python3
"""Write an SU2 (v8) compressible RANS config for a 2D aerofoil mesh written by sfhm2d_v7 --su2.
Defaults = NASA TMR NACA 0012 validation: M 0.15, Re 6e6 (chord 1), alpha 10, SA, adiabatic wall.

usage: su2_case_v1.py CASE_DIR [--aoa 10] [--mach 0.15] [--re 6e6] [--model SA|SST] [--iters 20000]
writes CASE_DIR/turb.cfg (mesh: CASE_DIR/mesh.su2, markers wall / farfield)
"""
import argparse, os
ap = argparse.ArgumentParser()
ap.add_argument('case'); ap.add_argument('--aoa', type=float, default=10.0); ap.add_argument('--mach', type=float, default=0.15)
ap.add_argument('--re', type=float, default=6e6); ap.add_argument('--model', default='SA', choices=['SA', 'SST'])
ap.add_argument('--iters', type=int, default=20000); ap.add_argument('--cfl', type=float, default=10.0)
ap.add_argument('--mg', type=int, default=3, help='agglomeration multigrid levels (0 = off)')
a = ap.parse_args()
cfg = f"""% SU2 RANS, TMR NACA 0012 conditions (generated by su2_case_v1.py)
SOLVER= RANS
KIND_TURB_MODEL= {a.model}
MATH_PROBLEM= DIRECT
RESTART_SOL= NO
MACH_NUMBER= {a.mach}
AOA= {a.aoa}
SIDESLIP_ANGLE= 0.0
INIT_OPTION= REYNOLDS
FREESTREAM_OPTION= TEMPERATURE_FS
FREESTREAM_TEMPERATURE= 300.0
REYNOLDS_NUMBER= {a.re}
REYNOLDS_LENGTH= 1.0
REF_ORIGIN_MOMENT_X= 0.25
REF_ORIGIN_MOMENT_Y= 0.0
REF_ORIGIN_MOMENT_Z= 0.0
REF_LENGTH= 1.0
REF_AREA= 1.0
REF_DIMENSIONALIZATION= FREESTREAM_VEL_EQ_ONE
FLUID_MODEL= STANDARD_AIR
VISCOSITY_MODEL= SUTHERLAND
MARKER_HEATFLUX= ( wall, 0.0 )
MARKER_FAR= ( farfield )
MARKER_PLOTTING= ( wall )
MARKER_MONITORING= ( wall )
NUM_METHOD_GRAD= WEIGHTED_LEAST_SQUARES
CFL_NUMBER= {a.cfl}
CFL_ADAPT= YES
CFL_ADAPT_PARAM= ( 0.5, 1.2, {a.cfl}, 1000.0 )
LINEAR_SOLVER= FGMRES
LINEAR_SOLVER_PREC= ILU
LINEAR_SOLVER_ERROR= 1E-4
LINEAR_SOLVER_ITER= 20
MGLEVEL= {a.mg}
MGCYCLE= W_CYCLE
MG_PRE_SMOOTH= ( 1, 2, 3, 3 )
MG_POST_SMOOTH= ( 0, 0, 0, 0 )
MG_CORRECTION_SMOOTH= ( 0, 0, 0, 0 )
MG_DAMP_RESTRICTION= 0.75
MG_DAMP_PROLONGATION= 0.75
CONV_NUM_METHOD_FLOW= ROE
MUSCL_FLOW= YES
SLOPE_LIMITER_FLOW= NONE
TIME_DISCRE_FLOW= EULER_IMPLICIT
CONV_NUM_METHOD_TURB= SCALAR_UPWIND
MUSCL_TURB= NO
TIME_DISCRE_TURB= EULER_IMPLICIT
ITER= {a.iters}
CONV_FIELD= RMS_DENSITY
CONV_RESIDUAL_MINVAL= -11
CONV_STARTITER= 10
MESH_FILENAME= mesh.su2
MESH_FORMAT= SU2
SCREEN_OUTPUT= ( INNER_ITER, RMS_DENSITY, RMS_NU_TILDE, LIFT, DRAG )
HISTORY_OUTPUT= ( ITER, RMS_RES, AERO_COEFF )
SCREEN_WRT_FREQ_INNER= 100
OUTPUT_FILES= ( RESTART, SURFACE_CSV )
OUTPUT_WRT_FREQ= 5000
CONV_FILENAME= history
SURFACE_FILENAME= surface_flow
"""
if a.model == 'SST':
    cfg = cfg.replace('RMS_NU_TILDE', 'RMS_TKE')
open(os.path.join(a.case, 'turb.cfg'), 'w').write(cfg)
print('wrote', os.path.join(a.case, 'turb.cfg'))
